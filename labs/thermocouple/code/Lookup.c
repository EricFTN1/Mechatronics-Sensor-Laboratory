float AnalogToTemp(float analog) {
    int i = 0; // Row index
    int k = 0; // Column index
    int j = 0; // Interpolate index
    while (i < 39)
    {  // Stop at 39 to avoid overflow with k+1 check
        float test2 = LookupTable[i][k];
        float test3 = LookupTable[i][k+1];

        if ((test2 < analog) && (analog < test3))
        {
            float interval = (test3 - test2) / 10;  // Divide the range into 10 parts
            for (j = 0; j < 10; j++)
            {
                float lowerBound = test2 + interval * j;
                float upperBound = test2 + interval * (j + 1);
                if ((lowerBound <= analog) && (analog <= upperBound))
                {
                    // Interpolate temperature: base temp + integer offset + decimal offset
                    float tempReturn = LookupTable[i][0] + k + (0.1 * j);
                    return tempReturn;  // Return interpolated temperature
                }
            }
        }
        k++;
        if (k == 11)
        {  // Move to the next row if column limit (11) is reached
            k = 0;
            i++;
        }
    }
    return -1;  // Return -1 or another error code if not found
}

float TempToAnalog(int Tempature){
    onesPlace = Tempature % 10;
    num = Tempature - (Tempature % 10);
    int i =0;
    while (LookupTable[i][0] != num){
        i++;
    }
    if (num > 0)      //pos num
    {
        test = LookupTable[i][onesPlace+1];
        return test;
    }
    else if (num < 0) //neg num
    {
        test = LookupTable[i][onesPlace+colSize-1];
        return test + 4;
    }
    else if (num == 0)  //zero case
    {
        if (onesPlace < 0) //neg onesplace
        {
            test = LookupTable[i][onesPlace+colSize-1];
            return test;
        }
        if (onesPlace > 0) //pos onesplace
        {
            test = LookupTable[i+1][onesPlace+1];
            return test ;
        }
        else{
            test = LookupTable[i][colSize-1];
            return test ;
        }

    }
    else{
        return -1;
    }
}




